#Operadores Aritméticos
print(5+2) #Soma
print(5-2) #Subtração
print(5*2) #Multiplicação
print(5/2) #Divisão
print(5//2) #Divisão inteira
print(5%2) #Resto da divisão
print(5**2) #Potência
print(2**0.5) #Raiz quadrada
#Operadores Relacionais
print(5 == 5) #Igualdade
print(5 != 5) #Diferença
print(5 > 5) #Maior que
print(5 < 5) #Menor que
print(5 >= 5) #Maior ou igual 
print(5 <= 5) #Menor ou igual
#Operadores de Atribuição Compostos
x = 10
x += 5  # x = x + 5 = 15
x -= 3  # x = x - 3 = 12
x *= 2  # x = x * 2 = 24
x /= 4  # x = x / 4 = 6.0
x //= 2  # x = x // 2 = 3.0
x %= 2  # x = x % 2 = 1.0
x **= 2  # x = x ** 2 = 1.0

